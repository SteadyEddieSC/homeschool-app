import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
const root = process.cwd();
const repo = path.resolve(root, '..');
function assert(value, message) { if (!value) throw new Error(message); }
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
assert(pkg.version === '11.0.0-rc.1', 'package release must be rc.1');
for (const name of ['migration:rehearse','readiness:report','vendor-exit:verify']) assert(pkg.scripts?.[name], `missing ${name}`);
for (const dependencies of [pkg.dependencies,pkg.devDependencies]) for (const version of Object.values(dependencies ?? {})) assert(/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(String(version)), 'dependencies must be pinned');
const migrationScript = await readFile(path.join(root, 'scripts/migration-rehearsal.mjs'), 'utf8');
for (const text of ['synthetic', 'rehearsal', 'dryRunWrites', 'productionCutover']) assert(migrationScript.includes(text), `migration rehearsal missing ${text}`);
const readiness = await readFile(path.join(root, 'scripts/production-readiness.mjs'), 'utf8');
for (const text of ["decision: 'not-approved'", 'automatedPromotionAllowed: false', 'owner-cutover-approval']) assert(readiness.includes(text), `readiness report missing ${text}`);
const vendor = await readFile(path.join(root, 'scripts/vendor-exit-rehearsal.mjs'), 'utf8');
for (const text of ['checksumMatched: true','providerTokensIncluded: false','passwordsIncluded: false']) assert(vendor.includes(text), `vendor exit missing ${text}`);
const migrations = (await readdir(path.join(root, 'supabase/migrations'))).filter((name) => name.endsWith('.sql')).sort();
assert(migrations.at(-1) === '202608040009_v11_migration_rehearsal.sql', 'migration 009 must be latest');
const migration = await readFile(path.join(root, 'supabase/migrations/202608040009_v11_migration_rehearsal.sql'), 'utf8');
for (const text of ['migration_import_receipts','production_readiness_decisions','enable row level security','production_cutover_approved']) assert(migration.includes(text), `migration 009 missing ${text}`);
const worker = await readFile(path.join(root, 'worker/index.ts'), 'utf8');
assert(worker.includes("11.0.0-rc.1"), 'worker release mismatch');
assert(worker.includes('productionCutover: false'), 'production cutover must remain false');
const runtime = await readFile(path.join(root, 'src/lib/supabase.ts'), 'utf8');
assert(runtime.includes("release: '11.0.0-rc.1'"), 'runtime release mismatch');
assert(runtime.includes("publishableKey.startsWith('sb_secret_')"), 'browser must reject secret keys');
const workflow = await readFile(path.join(repo, '.github/workflows/validate-v11.yml'), 'utf8');
assert(workflow.includes('v11-rc1-migration-rehearsal'), 'CI must upload rc.1 evidence');
assert(workflow.includes('beaufort-learning-harbor-v11.0.0-rc.1-preview'), 'CI must upload rc.1 preview');
const pointer = JSON.parse(await readFile(path.join(root, '../source/current-release.json'), 'utf8'));
assert(String(pointer.manifest).includes('v10.43'), 'v10.43 fallback pointer changed');
console.log('v11 rc.1 boundary checks passed');
